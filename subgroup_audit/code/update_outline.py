"""Populate the OUP conference outline from verified CPU outputs when present.

No external model results are invented. Public-noise preview is distinctly
sourced; subgroup panels remain pending until execution.json is complete.
"""
import json,re
from pathlib import Path
import pandas as pd,numpy as np
from common import ROOT,sha

def esc(s):return str(s).replace('_',r'\_').replace('%',r'\%').replace('&',r'\&')
def update():
 dest=ROOT/'conference';out=ROOT/'results';finished=False
 state=out/'execution.json'
 if state.exists() and json.loads(state.read_text()).get('complete'):
  hashes=json.loads((out/'result_CSV_sha256.json').read_text())
  for f,digest in hashes.items():
   if sha(out/f)!=digest:raise ValueError('Result table changed: '+f)
  finished=True
 noise=pd.read_csv(out/('noise_ceiling_by_dataset.csv' if finished else 'public_data_noise_ceiling.csv'))
 rows=[]
 for r in noise.itertuples():
  if np.isfinite(r.Pearson_noise_ceiling):rows.append(esc(r.dataset)+' & '+f'{r.Pearson_noise_ceiling:.3f} [{r.ceiling_ci95_low:.3f}, {r.ceiling_ci95_high:.3f}]'+r' \\')
  else:rows.append(esc(r.dataset)+r' & Not identifiable \\')
 provenance='Recomputed on the completed Wahab eligible population.' if finished else 'Calculated here on the prepared public v2 population; no model scores used. Wahab will recompute and verify the applicable population.'
 tex=r'''\begin{table}[t]
\caption{Classical additive-error Pearson ceilings, with 95\% genomic-cluster bootstrap intervals. These are approximate measurement ceilings, not maximum sign accuracies.}\label{tab:noise}
\centering\begin{tabular}{ll}\toprule
Study & Ceiling (95\% interval) \\\midrule
'''+ '\n'.join(rows)+r'''
\bottomrule\end{tabular}
\end{table}
'''+provenance+'\n'
 (dest/'noise_results.tex').write_text(tex)
 if finished:
  t=pd.read_csv(out/'subgroup_tests.csv');formal=t.loc[t.formal_external];n=int((formal.p_Holm.lt(.05)&formal.evaluable).sum());ne=int((~formal.evaluable).sum())
  text=f'The CPU follow-up completed all 70 fixed external test slots; {ne} were not estimable and retained as p=1 in the correction family. {n} contrasts met the declared Holm threshold. Each identified contrast must be interpreted using its direction, population and retained-opportunity denominator; the original primary FAIL is unchanged. Full estimates and intervals appear in the generated results table.'
 else:text='Borzoi source-only policy testing, source-family diagnostics, model contrasts and the70-test subgroup family remain pending on the existing Wahab scores. No new GPU inference is needed. The completed original Enformer failure does not imply an unobserved Borzoi failure.'
 (dest/'subgroup_status.tex').write_text(text+'\n')
 abstract='''Motivation: Strong performance on saturation-mutagenesis benchmarks does not establish that reliability rules transfer to independent regulatory-variant assays. We audit frozen sequence-model forecasts and source-trained confidence filtering under this change in evaluation setting.
Results: At matched within-block retention budgets, the completed Enformer DNASE audit increased Abell retained sign error by 2.1 percentage points (95% CI 0.7 to 3.6). Ulirsch error reduction was -0.3 points (95% CI -6.5 to 6.7), resolving neither gain nor harm. The original two-study transfer criterion failed. A locked follow-up separates promoter-like and enhancer-like genomic signatures, effect strength, Enformer/Borzoi readouts, cell matching and replicate noise, with Holm correction across 70 fixed external tests. Approximate Pearson measurement ceilings are 0.667 for Abell and 0.699 for Ulirsch; Kircher's full ceiling is not identifiable. Subgroup results remain pending, and no conclusion is generalized to every readout, confidence method or clinical use.
Availability and Implementation: A CPU reproducibility package accompanies this draft; a permanent public archive will be assigned before submission. It reuses completed open-model scores and excludes AlphaGenome outputs from fitting and analysis.
Contact: spath004@odu.edu.
Supplementary Information: Complete correction, provenance and retention tables are generated by the audit package.'''
 if finished:abstract=abstract.replace('Subgroup results remain pending, and no conclusion',f'The follow-up completed all 70 test slots; {n} contrasts passed Holm correction. No conclusion')
 blocks=[]
 for line in abstract.splitlines():
  if not line:continue
  heading,body=line.split(':',1);blocks.append(r'\textbf{'+heading+':} '+body.strip().replace('%',r'\%'))
 (dest/'abstract.tex').write_text('\\abstract{'+r'\\'.join(blocks)+'}\n')
 # Word count excludes the LaTeX commands and must stay within the CFP limit.
 count=len(re.findall(r"\b[\w'-]+\b",abstract))
 if count>250:raise ValueError('Structured abstract exceeds250 words: '+str(count))
 (dest/'abstract_plain.txt').write_text(abstract+'\n');(dest/'abstract_word_count.txt').write_text(str(count)+' words (including headings)\n')
 print('Conference outline populated. Subgroup results:', 'COMPLETE' if finished else 'PENDING','; abstract words:',count)
if __name__=='__main__':update()
